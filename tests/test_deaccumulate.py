    def test_quarterly(self):
        out = detect_cashflow_period_basis("CONDENSED STATEMENTS OF CASH FLOWS\nThree Months Ended March 28, 2026")
        self.assertEqual([f["basis"] for f in out], ["quarterly"])

    def test_ytd_6m(self):
        out = detect_cashflow_period_basis("Six Months Ended March 28, 2026")
        self.assertEqual([f["basis"] for f in out], ["ytd_6m"])

    def test_ytd_9m(self):
        out = detect_cashflow_period_basis("Nine Months Ended June 27, 2026")
        self.assertEqual([f["basis"] for f in out], ["ytd_9m"])

    def test_annual(self):
        out = detect_cashflow_period_basis("Fiscal Year Ended September 27, 2026")
        self.assertEqual([f["basis"] for f in out], ["annual"])

