def _cf(_id, concept, label=None, statement_type="cashflow"):
    return {
        "_id": _id,
        "concept": concept,
        "taxonomy_key": concept,
        "label": label or concept,
        "statement_type": statement_type,
    }


CF_CONCEPTS = [
    _cf("cf1", "us-gaap:NetCashProvidedByUsedInOperatingActivities",
        "Net cash provided by operating activities"),
    _cf("cf2", "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment",
        "Payments to acquire property, plant and equipment"),
    _cf("cf3", "us-gaap:CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalents",
        "Cash, cash equivalents, restricted cash, and restricted cash equivalents"),
    _cf("bs1", "us-gaap:CashAndCashEquivalentsAtCarryingValue",
        "Cash and cash equivalents at carrying value", statement_type="balancesheet"),
]


class TestClassifyKind(unittest.TestCase):
    def test_flow(self):
        self.assertEqual(classify_cashflow_kind(
            "NetCashProvidedByUsedInOperatingActivities",
            "Net cash provided by operating activities",
            "Cash generated by operating activities"), "flow")

    def test_ending_via_filing_label(self):
        self.assertEqual(classify_cashflow_kind(
            "CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalents",
            "Cash, cash equivalents, restricted cash, and restricted cash equivalents",
            "Cash, cash equivalents and restricted cash, ending balances"), "ending")

    def test_beginning_via_filing_label(self):
        self.assertEqual(classify_cashflow_kind(
            "CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalents",
            "Cash, cash equivalents, restricted cash, and restricted cash equivalents",
            "Cash, cash equivalents and restricted cash, beginning balances"), "beginning")

    def test_ending_via_concept_name(self):
        self.assertEqual(classify_cashflow_kind(
            "CashAndCashEquivalentsEndingBalance", ""), "ending")

    def test_beginning_via_concept_name(self):
        self.assertEqual(classify_cashflow_kind(
            "CashAndCashEquivalentsBeginningBalance", ""), "beginning")

    def test_cash_snapshot_without_filing_label(self):
        self.assertEqual(classify_cashflow_kind(
            "us-gaap:CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalents",
            "Cash, Cash Equivalent, Restricted Cash, and Restricted Cash Equivalent, Continuing Operation"), "ending")

    def test_cash_flow_period_increase_decrease(self):
        self.assertEqual(classify_cashflow_kind(
            "us-gaap:CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalentsPeriodIncreaseDecreaseIncludingExchangeRateEffect",
            "Cash, Cash Equivalent, Period Increase (Decrease)"), "flow")


